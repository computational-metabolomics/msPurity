#' @title Spectral matching for LC-MS/MS datasets
#' @aliases spectralMatching
#' @description
#' **General**
#'
#' Perform spectral matching to spectral libraries for an LC-MS/MS dataset.
#'
#' With \code{format = "parquet"}, search a Parquet results dataset against a
#' \code{Spectra} library or a converted dataset. The default SQLite route
#' searches a query SQLite database against a library SQLite database.
#'
#' The SQLite schema of the spectral database can be detailed Schema details can be found
#' [here](https://bioconductor.org/packages/release/bioc/vignettes/msPurity/inst/doc/msPurity-spectral-datatabase-schema.html).
#'
#' The query spectral-database in most cases should contain be the "unknown" spectra database generated the msPurity
#' function createDatabase as part of a msPurity-XCMS data processing workflow.
#'
#' The library spectral-database in most cases should contain the "known" spectra from either public or user generated resources.
#' The library SQLite database by default contains data from MoNA including Massbank, HMDB, LipidBlast and GNPS.
#' A larger database can be downloaded from [here](https://github.com/computational-metabolomics/msp2db/releases).
#' To create a user generated library SQLite database the following tool can be used to generate a SQLite database
#' from a collection of MSP files: [msp2db](https://github.com/computational-metabolomics/msp2db/releases).
#' It should be noted though, that as long as the schema of the spectral-database is as described [here ](https://bioconductor.org/packages/release/bioc/vignettes/msPurity/inst/doc/msPurity-spectral-database-vignette.html), then any database can be used
#' for either the library or query -  even allowing for the same database to be used.
#'
#' The spectral matching functionality has four main components, spectral filtering, spectral alignment, spectral matching,
#' and summarising the results.
#'
#' Spectral filtering is simply filtering both the library and query spectra to be search against (e.g. choosing
#' the library source, instrument, retention time, precursor PPM tolerance etc).
#'
#' The spectral alignment stage involves aligning the query peaks to the library peaks. The approach used is similar
#' to modified pMatch algorithm described in Zhou et al 2015.
#'
#' The spectral matching of the aligned spectra is performed against a combined intensity and m/z weighted vector - created for both
#' the query and library spectra (wq and wl). See below:
#'
#' \deqn{w=intensity^x * mz^y}
#'
#' Where x and y represent weight factors, defaults to *x*=0.5 and *y*=2 as per MassBank. These can be adjusted by
#' the user though.
#'
#' The aligned weighted vectors are then matched using dot product cosine, reverse dot product cosine and the composite dot product.
#' See below for dot product cosine equation.
#'
#' \deqn{dpc =  wq * wl / \sqrt{\sum wq^2} * \sqrt{\sum wl^2}}
#'
#' See the vigenttes for more details regarding matching algorithms used.
#'
#' **Example LC-MS/MS processing workflow**
#'
#'  * Purity assessments
#'    +  (mzML files) -> purityA -> (pa)
#'  * XCMS processing
#'    +  (mzML files) -> xcms.findChromPeaks -> (optionally) xcms.adjustRtime -> xcms.groupChromPeaks -> (xcmsObj)
#'    +  --- *Older versions of XCMS* --- (mzML files) -> xcms.xcmsSet -> xcms.group -> xcms.retcor -> xcms.group -> (xcmsObj)
#'  * Fragmentation processing
#'    + (xcmsObj, pa) -> frag4feature -> filterFragSpectra -> averageAllFragSpectra -> createDatabase -> **spectralMatching** -> (sqlite spectral database)
#'
#'
#'
#'
#' @param q_dbPth An experimental \code{Spectra} object, or the path to a
#'     query database generated by \code{createDatabase()}.
#' @param l_dbPth For SQLite, the library database path (defaults to the msPurityData library).
#'     For Parquet, supply a \code{Spectra} object from any backend, a converted Parquet library
#'     path, or a Parquet results dataset path. To search a generic MsBackendParquet dataset,
#'     open it as a \code{Spectra} object. The search uses its current subset and peak processing.
#'
#' @param q_purity character; Precursor ion purity threshold for the query spectra
#' @param q_ppmProd numeric; ppm tolerance for query product
#' @param q_ppmPrec numeric; ppm tolerance for query precursor
#' @param q_raThres numeric; Relative abundance threshold for query spectra
#' @param q_pol character; Polarity of query spectra ('positive', 'negative', NA).
#' @param q_instrumentTypes vector; Instrument types for query spectra.
#' @param q_instruments vector; Instruments for query spectra (note that this is used in combination with q_instrumentTypes - any
#'                              spectra matching either q_instrumentTypes or q_instruments will be used).
#' @param q_sources vector; Sources of query spectra (e.g. massbank, hmdb).
#' @param q_spectraTypes character; Spectra types of query spectra to perfrom spectral matching e.g. ('scan', 'av_all', 'intra', 'inter')
#' @param q_pids vector; pids for query spectra (correspond to column 'pid; in s_peak_meta)
#' @param q_rtrange vector; retention time range (in secs) of query spectra, first value mininum time and second value max e.g. c(0, 10) is between 0 and 10 seconds
#' @param q_spectraFilter boolean; For query spectra, if prior filtering performed with msPurity, flag peaks will be removed from spectral matching
#' @param q_xcmsGroups vector; XCMS group ids for query spectra
#' @param q_accessions vector; accession ids to filter query spectra
#'
#' @param l_purity character; Precursor ion purity threshold for the library spectra (uses interpolated purity - inPurity)
#' @param l_ppmProd numeric; ppm tolerance for library product
#' @param l_ppmPrec numeric; ppm tolerance for library precursor
#' @param l_raThres numeric; Relative abundance threshold for library spectra
#' @param l_pol character; Polarity of library spectra ('positive', 'negative', NA)
#' @param l_instrumentTypes vector; Instrument types for library spectra.
#' @param l_instruments vector; Instruments for library spectra (note that this is used in combination with q_instrumentTypes - any
#'                              spectra matching either q_instrumentTypes or q_instruments will be used).
#' @param l_sources vector; Sources of library spectra (e.g. massbank, hmdb).
#' @param l_spectraTypes vector; Spectra type of library spectra to perfrom spectral matching with e.g. ('scan', 'av_all', 'intra', 'inter')
#' @param l_pids vector; pids for library spectra (correspond to column 'pid; in s_peak_meta)
#' @param l_rtrange vector; retention time range (in secs) of library spectra, first value mininum time and second value max e.g. c(0, 10) is between 0 and 10 seconds
#' @param l_spectraFilter boolean; For library spectra, if prior filtering performed with msPurity, flag peaks will be removed from spectral matching
#' @param l_xcmsGroups vector; XCMS group ids for library spectra
#' @param l_accessions vector; accession ids to filter library spectra
#'
#' @param usePrecursors boolean; If TRUE spectra will be filtered by similarity of precursors based on ppm range defined by l_ppmPrec and q_ppmPrec
#' @param raW numeric; Relative abundance weight for spectra (default to 0.5 as determined by massbank for ESI data)
#' @param mzW numeric; mz weight for spectra (default to 2 as determined by massbank for ESI data)
#' @param rttol numeric ; Tolerance in time range between the library and query spectra retention time
#'
#' @param cores numeric; Number of cores to use
#' @param updateDb boolean; Update the Query SQLite database with the results
#' @param copyDb boolean; If updating the database - perform on a copy rather thatn the original query database
#' @param outPth character; If copying the database - the path of the new database file
#' @param format character; \code{"sqlite"} (the default) matches SQLite databases as described above. Writing
#'               results with \code{updateDb = TRUE} raises a deprecation warning: SQLite output is frozen.
#'               \code{"parquet"} (experimental) matches the averaged spectra (and, with \code{q_spectraTypes = "scan"},
#'               the referenced MS2 scans) of a Parquet results dataset in \code{q_dbPth}, written by
#'               \code{createDatabase(format = "parquet")}, against a \code{Spectra} library, a converted Parquet library dataset
#'               (see \code{convertLibraryToParquet()}) or another results dataset. Scores are computed exactly as for
#'               SQLite. With \code{updateDb = TRUE} the matches are added to the results dataset as identification
#'               evidence, with long-form scores, compounds and per-query coverage; with \code{copyDb = TRUE} they are
#'               added to a copy at \code{outPth} instead. Arguments that select spectra of a SQLite database only
#'               (\code{q_pids}, \code{q_accessions}, \code{q_instruments}, \code{q_instrumentTypes}, \code{q_sources},
#'               \code{q_raThres}, \code{l_raThres}, \code{l_pids}) are refused when set.
#' @param topn integer (Parquet or Spectra queries); keep, per query spectrum, the matches ranked \code{topn} or better by dot
#'             product cosine. Tied scores share a rank, and every match tied at the cut is kept. The cut and its
#'             boundary score are recorded in the dataset. \code{NA} keeps every match.
#' @param sourcePaths named character (parquet only); source key -> location, for a study dataset that has moved since
#'                    the results dataset was written.
#'
#' @param libraryVersion Optional release name for a \code{Spectra} library. Saved evidence
#'     references an external library and its native identifiers. An unnamed release is
#'     labelled \code{"Spectra"}. The returned \code{lpid} is the position in the supplied object.
#' @param libraryChecksum Optional SHA-256 digest of the release, supplied as 64 hexadecimal
#'     digits with an optional \code{sha256:} prefix. The digest is recorded as supplied by the
#'     caller. Without a digest each search records a separate source.
#'
#' @param param Optional \code{\link{SpectralMatchingParam}} for a Spectra query.
#'     Without it the four scalar ppm arguments set the tolerances. Explicit
#'     scalar ppm settings must agree with a supplied parameter object.
#' @param referenceRole For a Spectra query and a Spectra reference, use
#'     \code{"experimental"} (default) or \code{"library"}. For a Parquet
#'     path the manifest determines the role. A results path supplies the
#'     processed spectra from \code{\link{readProcessedSpectra}}.
#'
#' @section Experimental Spectra queries:
#' Supply measured or consensus MS2-MS4 spectra directly on either
#' experimental side. Each scored pair passes the metadata checks described
#' in \code{\link{scoreSpectrumPair}}. Keep parent scans in the object to make
#' measured ancestry available. Both objects retain their supplied selections
#' and queued peak processing, including subsets from readProcessedSpectra().
#' By default the entire selection is considered, with no polarity restriction.
#' Use q_pol, l_pol, q_rtrange, l_rtrange, rttol or library l_accessions to
#' narrow the comparison. The topn cut includes all ties at its boundary.
#' These in-memory searches require an explicit reference and usePrecursors
#' set to TRUE. Database writes and database-specific selectors are unsupported.
#'
#' The result contains query and reference Spectra objects, referenceRole and
#' matchedResults (NULL when no hit is retained). Each hit includes one-based
#' queryIndex and referenceIndex into those objects, available run, native
#' and dataset identifiers, library accession, MS level, compatibility reason,
#' six scores and within-query rank. Use the indices to retrieve the original
#' acquisition and provenance fields, including for anonymous spectra.
#'
#' Each retained hit identifies its \code{queryType} and \code{referenceType}
#' as \code{measured}, \code{consensus} or \code{library}. Join the hit to
#' \code{queryStatus} by \code{queryIndex}. This table has one row per supplied
#' query, including duplicates, in input order. A \code{filtered} query fell
#' outside the requested polarity or retention-time selection. An
#' \code{invalid_query} lacks a supported MS level or valid precursor mass.
#' For a valid query, \code{no_eligible_reference} means no reference passed
#' selection and compatibility checks. An \code{unscorable} query had eligible
#' references but no pair had usable peaks on both sides. A \code{scored} query
#' can still have zero retained hits after the rank cut, for example with
#' \code{topn = 0}. Inspect \code{reason}, \code{nEligible}, \code{nScored}
#' and \code{nRetained} to distinguish these outcomes.
#'
#' For experimental pairs, \code{sharedMeasurement} and \code{sharedSourceFile}
#' each report TRUE for established overlap, FALSE for known disjoint sources
#' and NA when the available identities cannot decide. Two scans can share a
#' file while having distinct measurement identities. The file is identified
#' by its recorded absolute origin path or URI, or by a run within an identified
#' Parquet dataset. Within that scope use the dataset spectrum ID, native ID or
#' acquisition number, in that order when both sides have it. A bare file name,
#' local feature link or unqualified scan number cannot establish overlap.
#' External library entries have unknown measurement provenance.
#'
#' Inspect \code{sourceMeasurements} by \code{side} ("query" or "reference")
#' and \code{inputIndex}. Each participating spectrum lists its distinct measured
#' contributors once, with their file, dataset, run and scan identifiers.
#' \code{fileComplete} and \code{measurementComplete} describe the available
#' identities for the whole spectrum. An unknown branch is represented by missing
#' identifiers. For a consensus, the contributors supplied peaks to the stored
#' average, including through intermediate averages. Subsequent peak filtering
#' affects the score, while the reported provenance describes the stored average.
#'
#' For example, compare a contributing scan and a scan with a different precursor
#' against one consensus from the bundled LC-MS/MS data.
#' \preformatted{
#' pa <- readRDS(system.file("extdata", "tests", "purityA",
#'     "2_frag4feature_pa.rds", package = "msPurity"))
#' pa <- averageAllFragSpectra(pa, param = AverageFragSpectraParam(
#'     minfrac = 0, minnum = 0, snr = 0))
#' ref <- averagedSpectra(pa, legacy = FALSE)[1L]
#' scans <- groupedSpectra(pa, legacy = FALSE)
#' members <- averagePeakMembers(ref, ref$spectrumId, depth = "original")
#' measured <- match(members$pid[1L], scans$pid)
#' other <- which(abs(scans$precursorMz - ref$precursorMz) > 1)[1L]
#' res <- spectralMatching(scans[c(measured, other)], ref, q_ppmPrec = 50)
#' res$queryStatus[, c("queryIndex", "status", "nEligible", "nRetained")]
#' res$matchedResults[, c("queryIndex", "sharedMeasurement", "sharedSourceFile")]
#' subset(res$sourceMeasurements, side == "reference")
#' }
#' The contributing scan has both overlap flags set to TRUE. The second query
#' has status \code{no_eligible_reference} and zero retained hits.
#'
#' @section Spectra library variables:
#' Direct library searches use \code{precursorMz}, \code{polarity} (0 negative, 1 positive)
#' and \code{rtime} (seconds). The entry and compound names come from \code{name}, the
#' precursor type from \code{adduct}, and structure and mass from \code{inchikey},
#' \code{formula}, \code{smiles}, \code{inchi} and \code{exactmass}. Library filters use
#' \code{instrument}, \code{instrument_type}, \code{dataOrigin} and \code{precursorPurity}.
#' Corresponding stored \code{x_mspurity_*} variables take precedence when available.
#' Identifiers are chosen per spectrum from \code{accession}, \code{spectrumId} and
#' \code{splash}, in that order. Entries missing all three receive a SHA-256 identifier
#' derived from precursor mass, polarity and ordered peak values.
#'
#' Only the precursor index spans the full library. Candidate metadata and peaks are read
#' in batches, including when precursor filtering is disabled. The input can use any row
#' order. Memory for scoring results depends on the number of matches before the top-n cut.
#'
#' For example, given a Parquet results path \code{query_path}, search an MSP library directly:
#' \preformatted{
#' msp <- MsBackendMsp::MsBackendMsp()
#' lib <- Spectra::Spectra("library.msp", source = msp,
#'     mapping = Spectra::spectraVariableMapping(msp, "mona"))
#' spectralMatching(query_path, lib, format = "parquet", libraryVersion = "MoNA release")
#' }
#'
#' @param q_dbType character; Query database type for compound database can be either (sqlite, postgres or mysql)
#' @param q_dbName character; Query database name (only applicable for postgres and mysql)
#' @param q_dbHost character; Query database host (only applicable for postgres and mysql)
#' @param q_dbPort character; Query database port (only applicable for postgres and mysql)
#' @param q_dbUser character; Query database user (only applicable for postgres and mysql)
#' @param q_dbPass character; Query database pass - Note this is not secure! use with caution (only applicable for postgres and mysql)
#'
#' @param l_dbType character; Library database type for compound database can be either (sqlite, postgres or mysql)
#' @param l_dbName character; Library database name (only applicable for postgres and mysql)
#' @param l_dbHost character; Library database host (only applicable for postgres and mysql)
#' @param l_dbPort character; Library database port (only applicable for postgres and mysql)
#' @param l_dbUser character; Library database user (only applicable for postgres and mysql)
#' @param l_dbPass character; Library database pass - Note this is not secure! use with caution (only applicable for postgres and mysql)
#'
#' @return For a Spectra query, the list described under Experimental Spectra queries.
#' For a database query, a list containing the following elements
#'
#' **q_dbPth**
#'
#' Path of the query database (this will have been updated with the annotation results if updateDb argument used)
#'
#'**xcmsMatchedResults**
#'
#'  If the qeury spectra had XCMS based chromotographic peaks tables (e.g c_peak_groups, c_peaks) in the sqlite database - it will
#' be possible to summarise the matches for each XCMS grouped feature. The dataframe contains the following columns
#'
#' * lpid - id in database of library spectra
#' * qpid - id in database of query spectra
#' * dpc - dot product cosine of the match
#' * rdpc - reverse dot product cosine of the match
#' * cdpc - composite dot product cosine of the match
#' * mcount - number of matching peaks
#' * allcount - total number of peaks across both query and library spectra
#' * mpercent - percentage of matching peaks across both query and library spectra
#' * library_rt - retention time of library spectra
#' * query_rt - retention time of query spectra
#' * rtdiff - difference between library and query retention time
#' * library_precursor_mz - library precursor mz
#' * query_precursor_mz - query precursor mz
#' * library_precursor_ion_purity - library precursor ion purity
#' * query_precursor_ion_purity - query precursor ion purity
#' * library_accession -  library accession value (unique string or number given to eith MoNA or Massbank data entires)
#' * library_precursor_type - library precursor type (i.e. adduct)
#' * library_entry_name - Name given to the library spectra
#' * inchikey - inchikey of the matched library spectra
#' * library_source_name - source of the spectra (e.g. massbank, gnps)
#' * library_compound_name - name of compound spectra was obtained from
#'
#' **matchedResults**
#'
#' All matched results from the query spectra to the library spectra. Contains the same columns as above
#' but without the XCMS details. This table is useful to observe spectral matching results
#' for all MS/MS spectra irrespective of if they are linked to XCMS MS1 features.
#'
#' @return list of database details and dataframe summarising the results for the xcms features
#'
#' @examples
#' d <- S4Vectors::DataFrame(msLevel = 2L, precursorMz = 200)
#' d$mz <- list(c(50, 80))
#' d$intensity <- list(c(100, 20))
#' query <- Spectra::Spectra(d, source = Spectra::MsBackendMemory())
#' replicate <- query
#' spectralMatching(query, replicate)$matchedResults
#' libraryEntry <- query
#' libraryEntry$accession <- "example-1"
#' spectralMatching(query, libraryEntry, referenceRole = "library")$matchedResults
#'
#' #====== XCMS =================================
#' ## Read in MS data
#' #msmsPths <- list.files(system.file("extdata", "lcms", "mzML",
#' #           package="msPurityData"), full.names = TRUE, pattern = "MSMS")
#' #ms_data = readMSData(msmsPths, mode = 'onDisk', msLevel. = 1)
#'
#' ## Find peaks in each file
#' #cwp <- CentWaveParam(snthresh = 5, noise = 100, ppm = 10, peakwidth = c(3, 30))
#' #xcmsObj  <- xcms::findChromPeaks(ms_data, param = cwp)
#'
#' ## Optionally adjust retention time
#' #xcmsObj  <- adjustRtime(xcmsObj , param = ObiwarpParam(binSize = 0.6))
#'
#' ## Group features across samples
#' #pdp <- PeakDensityParam(sampleGroups = c(1, 1), minFraction = 0, bw = 30)
#' #xcmsObj <- groupChromPeaks(xcmsObj , param = pdp)
#'
#' #====== msPurity ============================
#' #pa  <- purityA(msmsPths)
#' #pa <- frag4feature(pa = pa, xcmsObj = xcmsObj)
#' #pa <- filterFragSpectra(pa, allfrag=TRUE)
#' #pa <- averageAllFragSpectra(pa)
#' #q_dbPth <- createDatabase(pa, xcmsObj, metadata=list('polarity'='positive','instrument'='Q-Exactive'))
#' #sm_result <- spectralMatching(q_dbPth, cores=4, l_pol='positive')
#'
#' td <- tempdir()
#' q_dbPth <- system.file("extdata", "tests", "db", "createDatabase_example.sqlite", package="msPurity")
#'
#' ## A small library with the spectra used here. Leave l_dbPth as NA to use the
#' ## full reference library, which is downloaded and cached on first use.
#' l_dbPth <- system.file("extdata", "tests", "library", "mini_library.sqlite", package="msPurity")
#'
#' rid <- paste0(paste0(sample(LETTERS, 5, TRUE), collapse=""),  paste0(sample(9999, 1, TRUE), collapse=""), ".sqlite")
#' sm_out_pth <- file.path(td, rid)
#'
#' result <- spectralMatching(q_dbPth, l_dbPth = l_dbPth, q_xcmsGroups = c(53, 89, 410), cores=1, l_accessions = c('PR100407', 'ML005101', 'CCMSLIB00003740024'),
#'                           q_spectraTypes = 'av_all',
#'                           updateDb = TRUE,
#'                           copyDb = TRUE,
#'                           outPth = sm_out_pth)
#'
#'
#' @md
#' @export
#' @import dbplyr
spectralMatching <- function(
                              q_dbPth,
                              l_dbPth=NA,

                              q_purity=NA,
                              q_ppmProd=10,
                              q_ppmPrec=5,
                              q_raThres=NA,
                              q_pol=NA,
                              q_instrumentTypes=NA,
                              q_instruments=NA,
                              q_sources=NA,
                              q_spectraTypes=c('av_all', 'inter'),
                              q_pids=NA,
                              q_rtrange=c(NA, NA),
                              q_spectraFilter=TRUE,
                              q_xcmsGroups=NA,
                              q_accessions=NA,

                              l_purity=NA,
                              l_ppmProd=10,
                              l_ppmPrec=5,
                              l_raThres=NA,
                              l_pol='positive',
                              l_instrumentTypes=NA,
                              l_instruments=NA,
                              l_sources=NA,
                              l_spectraTypes=NA,
                              l_pids=NA,
                              l_rtrange=c(NA, NA),
                              l_spectraFilter=FALSE,
                              l_xcmsGroups=NA,
                              l_accessions=NA,
                              usePrecursors=TRUE,
                              raW=0.5,
                              mzW=2,
                              rttol=NA,

                              q_dbType='sqlite',
                              q_dbName=NA,
                              q_dbHost=NA,
                              q_dbUser=NA,
                              q_dbPass=NA,
                              q_dbPort=NA,

                              l_dbType='sqlite',
                              l_dbName=NA,
                              l_dbHost=NA,
                              l_dbUser=NA,
                              l_dbPass=NA,
                              l_dbPort=NA,

                              cores=1,
                              updateDb=FALSE,
                              copyDb=FALSE,
                              outPth='sm_result.sqlite',
                              format=c('sqlite', 'parquet'),
                              topn=NA,
                              sourcePaths=NULL,
                              libraryVersion=NULL,
                              libraryChecksum=NULL,
                              param=NULL,
                              referenceRole=NULL){
  if (is(q_dbPth, "Spectra")) {
    return(.sm_search_spectra(as.list(environment()), names(match.call())[-1L]))
  }
  if (!is.null(param) || !is.null(referenceRole))
    stop("param and referenceRole require a Spectra query.", call. = FALSE)
  format <- match.arg(format)
  a <- as.list(environment())
  a[c("param", "referenceRole")] <- NULL
  if (format == 'parquet'){
    return(.spectralMatching_parquet(a))
  }
  if (is(l_dbPth, "Spectra") || !is.null(libraryVersion) || !is.null(libraryChecksum)){
    stop("Spectra libraries and their release information require format = 'parquet'.", call. = FALSE)
  }
  if (!is.na(topn)){
    stop("'topn' is only available with format = \"parquet\".", call. = FALSE)
  }
  res <- do.call(.spectralMatching_sqlite, a[names(formals(.spectralMatching_sqlite))])
  if (isTRUE(updateDb)){
    .msp_deprecate_sqlite('spectralMatching(updateDb = TRUE)')
  }
  res
}

